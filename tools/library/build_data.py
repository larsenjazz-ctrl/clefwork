"""Merge the library's sources into library/data.js (every piece, loaded when needed) and
src/library-index.js (a line a piece, bundled, so a quiz can choose pieces before the data loads).

The order is fixed: pieces are only ever added at the end, each with v, the library version it
arrived in, so a quiz code made with version n keeps choosing from the same pieces.

    python3 build_data.py OUT_LIBRARY_DIR OUT_INDEX_JS SOURCE.json [SOURCE.json ...]
"""
import json, re, sys

VERSION = 1
HAND = 'Entered for Clefwork — please proofread against a score before using it'


def tidy(p):
    p = dict(p)
    p.setdefault('v', 1)
    p.setdefault('score', '')
    p.setdefault('year', '')
    p.setdefault('license', 'Public domain')
    p.setdefault('source', HAND)
    parts = p.get('parts') or []
    p['bars'] = len(parts[0]['m']) if parts else 0
    # "John Bunnell Sumner, 1877" with year 1877 -> "John Bunnell Sumner"
    if p['year'] and p['by'].endswith(', ' + p['year']):
        p['by'] = p['by'][:-len(', ' + p['year'])]
    p['by'] = re.sub(r',?\s*circa\s+\d{4}$', '', p['by']).strip()
    for k in ('pages', 'life'):
        p.pop(k, None)
    return p


def main(outdir, index_js, *sources):
    pieces, seen = [], set()
    for s in sources:
        for p in json.load(open(s)):
            p = tidy(p)
            if p['id'] in seen:
                continue
            seen.add(p['id'])
            pieces.append(p)
    body = json.dumps(pieces, ensure_ascii=False, separators=(',', ':'))
    open(outdir + '/data.js', 'w').write(
        '/* Clefwork Library — every piece (see src/library.js for the format). Generated by tools/library/build_data.py. */\n'
        f'(function (root) {{ const MQ = (root.MQ = root.MQ || {{}}); MQ.LIBRARY_DATA = {body}; }})(typeof window !== "undefined" ? window : globalThis);\n')
    idx = [[p['id'], p['kind'], p['bars'], 1 if p['parts'] else 0, 1 if p['score'] else 0, p['v']] for p in pieces]
    open(index_js, 'w').write(
        '/* Clefwork Library — one line a piece: [id, kind, measures, can be heard, has a score, version].\n'
        '   Generated by tools/library/build_data.py; the pieces themselves are in library/data.js. */\n'
        '(function (root) {\n  const MQ = (root.MQ = root.MQ || {});\n'
        f'  MQ.LIBRARY_VERSION = {VERSION};\n'
        '  MQ.LIBRARY_INDEX = [\n' + ''.join(('    ' if i % 4 == 0 else ' ') + json.dumps(r, ensure_ascii=False, separators=(',', ':')) + (',\n' if i % 4 == 3 else ',') for i, r in enumerate(idx)) + '\n  ];\n'
        '})(typeof window !== \'undefined\' ? window : globalThis);\n')
    kinds = {}
    for p in pieces:
        kinds[(p['kind'], bool(p['parts']), bool(p['score']))] = kinds.get((p['kind'], bool(p['parts']), bool(p['score'])), 0) + 1
    print(len(pieces), 'pieces;', len(body) // 1024, 'KB of data')
    for k, v in sorted(kinds.items()):
        print(f'  {k[0]:9} heard={k[1]!s:5} score={k[2]!s:5} {v}')


if __name__ == '__main__':
    main(*sys.argv[1:])
